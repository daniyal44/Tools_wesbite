export function getAllAITools(): AITool[] {
  return AI_TOOLS_DATABASE;
}

export function getAIToolBySlug(slug: string): AITool | undefined {
  return AI_TOOLS_DATABASE.find((tool) => tool.slug === slug);
}

export function getAIToolsByCategory(categorySlug: string): AITool[] {
  return AI_TOOLS_DATABASE.filter((tool) => tool.category === categorySlug);
}

export function getAIToolsByLetter(letter: string): AITool[] {
  const l = letter.toUpperCase().trim();
  if (l === 'ALL') return AI_TOOLS_DATABASE;
  if (l === '#') {
    return AI_TOOLS_DATABASE.filter((tool) => !/^[A-Z]/i.test(tool.name));
  }
  return AI_TOOLS_DATABASE.filter((tool) => tool.name.toUpperCase().startsWith(l));
}

export function getRelatedAITools(tool: AITool, limit = 4): AITool[] {
  return AI_TOOLS_DATABASE
    .filter((t) => t.id !== tool.id && (t.category === tool.category || t.subcategory === tool.subcategory))
    .slice(0, limit);
}

export function getFeaturedAITools(): AITool[] {
  return AI_TOOLS_DATABASE.filter((tool) => tool.featured);
}

export function getTrendingAITools(): AITool[] {
  return AI_TOOLS_DATABASE.filter((tool) => tool.trending);
}

export function searchAITools(
  query = '',
  category = 'all',
  pricing = 'all',
  sortBy: 'traffic' | 'rating' | 'trending' | 'name' | 'newest' = 'traffic'
): AITool[] {
  let results = [...AI_TOOLS_DATABASE];

  if (category && category !== 'all') {
    results = results.filter((tool) => tool.category === category);
  }

  if (pricing && pricing !== 'all') {
    results = results.filter((tool) => tool.pricing === pricing);
  }

  if (query.trim()) {
    const q = query.toLowerCase().trim();
    results = results.filter(
      (tool) =>
        tool.name.toLowerCase().includes(q) ||
        tool.tagline.toLowerCase().includes(q) ||
        tool.description.toLowerCase().includes(q) ||
        tool.subcategory.toLowerCase().includes(q) ||
        tool.tags.some((tag) => tag.toLowerCase().includes(q))
    );
  }

  // Parse traffic numbers for sorting (e.g. "1.9B" -> 1900000000, "95M" -> 95000000, "3.8M" -> 3800000)
  const parseTraffic = (str: string): number => {
    const clean = str.trim().toUpperCase();
    if (clean.endsWith('B')) return parseFloat(clean) * 1_000_000_000;
    if (clean.endsWith('M')) return parseFloat(clean) * 1_000_000;
    if (clean.endsWith('K')) return parseFloat(clean) * 1_000;
    return parseFloat(clean) || 0;
  };

  switch (sortBy) {
    case 'traffic':
      results.sort((a, b) => parseTraffic(b.monthlyVisits) - parseTraffic(a.monthlyVisits));
      break;
    case 'rating':
      results.sort((a, b) => b.rating - a.rating);
      break;
    case 'trending':
      results.sort((a, b) => (b.trending ? 1 : 0) - (a.trending ? 1 : 0));
      break;
    case 'name':
      results.sort((a, b) => a.name.localeCompare(b.name));
      break;
    case 'newest':
      results.sort((a, b) => b.launchYear - a.launchYear);
      break;
  }

  return results;
}
